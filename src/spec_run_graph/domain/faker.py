def bruno_dynamic(faker_name: str) -> str | None:
    """'first_name' -> 'randomFirstName'; None when Bruno has no equivalent."""
    if faker_name in ALIASES:
        return ALIASES[faker_name]
    camel = "random" + "".join(part.capitalize() for part in faker_name.split("_"))
    if camel in BRUNO_DYNAMIC:
        return camel
    lowered = {v.lower(): v for v in BRUNO_DYNAMIC}
    return lowered.get(camel.lower())
